import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync('server.mjs','utf8');
const now=Date.now();
let snapshot={checkedAt:new Date(now).toISOString(),wireguard:{status:'connected',handshakeAgeSeconds:10,routingService:'active',policyRule:true,privateKey:'DO-NOT-EXPORT'}};
const line='+4960316868187';
const routing={checkedAt:snapshot.checkedAt,mappings:{[line]:'+491701234567'},hours:{},announcements:{[line]:{text:'Willkommen im Büro',id:'secret-file-id',secret:'DO-NOT-EXPORT'}},password:'DO-NOT-EXPORT'};
const env=vm.createContext({Date,fs:{readFileSync:p=>JSON.stringify(p.endsWith('pbx-status.json')?snapshot:routing)},path:{join:(...p)=>p.join('/')},storeDir:'/data',readRouting:()=>({available:true}),readNumbers:()=>[{e164:line,label:'Büro',extension:'100'}],normalizeRouteTarget:raw=>raw,allowedLines:[line],allowedExtensions:['100'],validateHours:x=>x});
vm.runInContext(source.slice(source.indexOf('function readInfrastructure('),source.indexOf('function queryCallHistory(')),env);
assert.equal(vm.runInContext('readInfrastructure().status',env),'connected');
assert(!JSON.stringify(vm.runInContext('readInfrastructure()',env)).includes('DO-NOT-EXPORT'));
snapshot.checkedAt=new Date(now-200000).toISOString();
assert.equal(vm.runInContext('readInfrastructure().status',env),'stale');
const exported=vm.runInContext('buildSettingsExport()',env);
assert.equal(exported.numbers[0].label,'Büro');
assert.equal(exported.numbers[0].target,'+491701234567');
assert.equal(exported.numbers[0].announcement.text,'Willkommen im Büro');
assert(!JSON.stringify(exported).includes('DO-NOT-EXPORT'));
assert(!JSON.stringify(exported).includes('secret-file-id'));
for(const route of ['/api/settings','/api/settings/export']){
 const start=source.indexOf("if(pathname==='"+route+"'");
 assert(source.slice(start,start+200).includes('if(!await authenticated(req))'));
}
const app=fs.readFileSync('public/app.js','utf8').split("nav.forEach(b=>b.addEventListener")[0];
const ui=vm.createContext({document:{querySelector:()=>({}),querySelectorAll:()=>[]},Date,Intl});
vm.runInContext(app,ui);
let html=vm.runInContext('screens.settings()',ui);
assert(html.includes('Nicht geprüft'));
assert(!html.includes('Später konfigurierbar'));
assert(html.includes('Einstellungen herunterladen'));
ui.data={checkedAt:new Date().toISOString(),wireguard:{status:'connected',handshakeAgeSeconds:20,routingService:'active',policyRule:true},access:{email:'<admin>',role:'Administrator'},routing:{available:true}};
vm.runInContext('settingsState=data',ui);
html=vm.runInContext('screens.settings()',ui);
assert(html.includes('Letzter Handshake vor 20 Sekunden'));
assert(html.includes('Vorbereitet'));
assert(html.includes('&lt;admin&gt;'));
assert(html.includes('href="#extensions"'));
console.log('System settings freshness, private-field exclusion, authenticated export and UI tests passed.');
