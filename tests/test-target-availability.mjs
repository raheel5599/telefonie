import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const app=fs.readFileSync('public/app.js','utf8').split("nav.forEach(b=>b.addEventListener")[0];
const env=vm.createContext({document:{querySelector:()=>({}),querySelectorAll:()=>[]},Date,Intl});
vm.runInContext(app,env);
const run=s=>vm.runInContext(s,env);
run("routingState={available:true,mappings:{'+4960316868187':'100'}};liveStatus={monitoring:'connected',registrations:[{id:'telekom-registration',status:'Registered'}],extensions:[{id:'100',configured:true,registered:false,online:false}]}");
let html=run('screens.numbers()');
assert(html.includes('Telekom registriert'));
assert(html.includes('Telefon/App offline'));
run('liveStatus.extensions[0].registered=true;liveStatus.extensions[0].online=null');
assert.equal(run('targetAvailability(lines[0]).label'),'Telefon/App angemeldet');
run('liveStatus.extensions[0].online=true');
assert.equal(run('targetAvailability(lines[0]).label'),'Telefon/App online');
run("liveStatus.monitoring='stale'");
assert.equal(run('targetAvailability(lines[0]).kind'),'neutral');
run("routingState.mappings[lines[0].e164]='+491701234567'");
assert.equal(run('targetAvailability(lines[0]).label'),'Externes Rufziel · Status nicht prüfbar');
run("callCache={source:{status:'connected'},stats:{total:1},calls:[{direction:'incoming',from:null,to:'+4960316868187',callerIdStatus:'unconfirmed',status:'failed',failureReason:'target-unavailable',startedAt:new Date().toISOString()}]}");
html=run('screens.calls()');
assert(html.includes('Anrufernummer nicht erfasst'));
assert(html.includes('Rufziel nicht erreichbar'));
console.log('Provider registration and actual target availability remain independent; caller and failure labels passed.');
