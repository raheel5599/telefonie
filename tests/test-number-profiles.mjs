import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const server=fs.readFileSync('server.mjs','utf8');
let saved=[],writes=0;
const env=vm.createContext({fs:{readFileSync:()=>JSON.stringify(saved),writeFileSync:(_,text)=>{saved=JSON.parse(text);writes++},renameSync:()=>{}},numbersPath:'numbers.json',process:{pid:1}});
vm.runInContext(server.slice(server.indexOf('function readStoredNumbers'),server.indexOf('const plansPath')),env);
const run=code=>vm.runInContext(code,env);
assert.equal(run('readNumbers().length'),3);
assert.throws(()=>run("saveNumberProfile({line:'+491701234567',label:'Other'})"));
assert.throws(()=>run("saveNumberProfile({line:'+4960316868187',label:' '})"));
assert.throws(()=>run("saveNumberProfile({line:'+4960316868187',label:'Bad\\nName'})"));
assert.equal(writes,0);
run("saveNumberProfile({line:'+4960316868187',label:' Büro   Friedberg ',extension:'999'})");
assert.equal(run('readNumbers()[0].label'),'Büro Friedberg');
assert.equal(run('readNumbers()[0].extension'),'100');
assert.equal(run('readNumbers()[1].label'),'TARIQ');
const app=fs.readFileSync('public/app.js','utf8').split("nav.forEach(b=>b.addEventListener")[0];
const ui=vm.createContext({document:{querySelector:()=>({}),querySelectorAll:()=>[]},Date,Intl});
vm.runInContext(app,ui);
vm.runInContext("lines[0].label='<Büro>';numberDrafts[lines[1].e164]='Noch nicht gespeichert'",ui);
const html=vm.runInContext('screens.numbers()',ui);
assert(html.includes('&lt;Büro&gt;'));
assert(!html.includes('<Büro>'));
assert(html.includes('Noch nicht gespeichert'));
assert(html.includes('data-number-hours="+4960316868187"'));
assert(html.includes('href="#forwards"'));
assert(!html.includes('erst mit sicherer PBX'));
console.log('Number profile validation, persistence, fixed provisioned numbers and escaped UI passed.');
